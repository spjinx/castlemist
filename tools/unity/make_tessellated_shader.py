"""Writes Castlemist/Shaders/GW2 Tessellated.shader from GW2.shader (2026-10-22).

The tessellated shader is Castlemist/GW2 with GPU tessellation (GW2Tess.cginc) in its forward and
shadow passes: the same properties, blocks and inspector, plus three tessellation properties, so a
material switches between the two keeping its values. Run it after any change to GW2.shader:

    python tools/unity/make_tessellated_shader.py
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent / "Castlemist" / "Shaders"
SRC, DST = HERE / "GW2.shader", HERE / "GW2 Tessellated.shader"


def main() -> int:
    s = SRC.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s.replace("\r\n", "\n")

    def once(old: str, new: str) -> None:
        nonlocal s
        if s.count(old) != 1:
            raise SystemExit(f"GW2.shader changed: expected one {old!r}")
        s = s.replace(old, new)

    once('Shader "Castlemist/GW2"', 'Shader "Castlemist/GW2 Tessellated"')
    once("        [Header(Cutout and burn edge (GW2 opacity, burnoff, burncol))]",
         "        [Header(Tessellation (PC))]\n"
         "        _TessEdgeLength (\"Edge length (pixels)\", Range(2, 50)) = 8\n"
         "        _TessMaxFactor (\"Max subdivision\", Range(1, 32)) = 12\n"
         "        _TessMaxDistance (\"Fade out by (Unity units)\", Float) = 60\n"
         "\n"
         "        [Header(Cutout and burn edge (GW2 opacity, burnoff, burncol))]")
    for vert, define in (("vert", "CM_PASS_FORWARDBASE"), ("vert", "CM_PASS_FORWARDADD"),
                         ("vertShadow", "CM_PASS_SHADOWCASTER")):
        block_start = s.index(f"#define {define}")
        head = s.rindex("CGPROGRAM", 0, block_start)
        body = s[head:block_start]
        body = body.replace("#pragma target 3.5", "#pragma target 4.6", 1)
        body = body.replace(f"#pragma vertex {vert}\n",
                            "#pragma vertex tessvert\n            #pragma hull tesshull\n"
                            "            #pragma domain tessdomain\n", 1)
        s = s[:head] + body + s[block_start:]
        inc = s.index('#include "GW2Core.cginc"', s.index(f"#define {define}"))
        end = inc + len('#include "GW2Core.cginc"')
        s = s[:end] + '\n            #include "GW2Tess.cginc"' + s[end:]
    once("    FallBack Off", '    FallBack "Castlemist/GW2"')
    header = ("// GENERATED by tools/unity/make_tessellated_shader.py from GW2.shader: edit GW2.shader and\n"
              "// rerun it. Castlemist/GW2 with GPU tessellation (GW2Tess.cginc) for the wave block; PC only\n"
              "// (shader model 4.6), Castlemist/GW2 where tessellation is unsupported.\n")
    DST.write_text((header + s).replace("\n", nl), encoding="utf-8", newline="")
    print("wrote", DST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
